"""Generated replay and complete structured in-memory evidence, emitted to stdout."""

import argparse
from dataclasses import fields, is_dataclass
from datetime import date, datetime
from enum import Enum
from fractions import Fraction
import json

from .domain import ExecutionLog, FinancialState, Goal, LivingPlan
from .lifecycle import DecisionEvaluation
from .reality import PlanReevaluation
from .story import STORY, run_story


def structured(value):
    if is_dataclass(value):
        return {"record_type": type(value).__name__, **{f.name: structured(getattr(value, f.name)) for f in fields(value)}}
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, Fraction):
        return {"numerator": value.numerator, "denominator": value.denominator}
    if isinstance(value, (date, datetime)):
        return value.isoformat()
    if isinstance(value, tuple):
        return [structured(v) for v in value]
    if value is None or type(value) in (str, int, bool):
        return value
    raise TypeError(f"Unsupported export type: {type(value)}")


def money(value):
    sign = "−" if value.minor_units < 0 else ""
    whole, minor = divmod(abs(value.minor_units), 100)
    return f"{value.currency.value} {sign}{whole:,}.{minor:02d}"


def ref(value):
    return f"{value.id} v{value.version}"


def markdown(snapshot):
    evaluation = snapshot.get(DecisionEvaluation, STORY.evaluation_ref)
    calc = evaluation.calculation
    receipt = next(r for r in snapshot.records if type(r) is ExecutionLog)
    reevaluation = next(r for r in snapshot.records if type(r) is PlanReevaluation)
    before_goal = snapshot.get(Goal, receipt.before_goal_ref)
    after_goal = snapshot.get(Goal, receipt.after_goal_ref)
    state = snapshot.get(FinancialState, snapshot.current_state_ref)
    plan = snapshot.get(LivingPlan, snapshot.current_plan_ref)
    rows = [
        "# FINVIS Phase 2 — Generated Deterministic Replay", "",
        "Generated by `python3 -B -m finvis.replay` from actual domain commands. All values are synthetic; storage is in-memory.", "",
        f"Decision: {ref(evaluation.decision_ref)}. Selected option: {ref(receipt.option_ref)}.",
        f"Liquidity before: {money(calc.trace.available_liquidity)}; planned after trip: {money(calc.liquidity_after_trip)}.",
        f"Monthly essentials: {money(calc.trace.monthly_essential_outflow)}.",
        f"Runway: {calc.runway_delta.before.months} → {calc.runway_delta.after.months} months; delta {calc.runway_delta.change_months} months (exact ratios).", "",
        "| If Line | Months | Without trip | With trip |", "|---|---:|---:|---:|",
    ]
    for line in evaluation.lines:
        p = line.projection
        rows.append(f"| {ref(line.if_line_ref)} | {p.unemployment_months} | {money(p.without_trip_balance)} | {money(p.with_trip_balance)} |")
    rows += ["", "## Authorized plan execution", "",
        f"Action {ref(receipt.action_ref)}; consent {ref(receipt.authorization_ref)}; result **{receipt.outcome.value}** at {receipt.recorded_at.isoformat()}.",
        f"Car target: **{before_goal.target_date} → {after_goal.target_date}**.",
        f"Plan: {ref(receipt.before_plan_ref)} → {ref(receipt.after_plan_ref)}. State references: {ref(receipt.before_state_ref)} → {ref(receipt.after_state_ref)}.",
        f"Changed fields: {', '.join(receipt.changed_fields)}.",
        "No money moved. Observed liquidity is unchanged; trip cost is an explicit planned outflow. Existing contribution amounts are preserved, not recalibrated.", "",
        "## Accepted employment reality", "",
        f"Event: {ref(reevaluation.event_ref)}. Employment: **{state.employment.status.value}**.",
        f"Monthly offer: **{money(state.employment.offer.monthly_income.value)}**; salary basis: {state.employment.offer.salary_basis.value}; start date: unspecified.",
        f"Materiality: {reevaluation.materiality.disposition.value} — {reevaluation.materiality.rationale}.",
        "Closed no-confirmed-offer If Lines: " + ", ".join(ref(r) for r in reevaluation.resolved_if_line_refs) + ".",
        "Original active versions remain in history; acceptance does not assert that work or pay has begun.",
        f"Continuous plan: {ref(reevaluation.before_plan_ref)} → {ref(plan.ref)}; current financial state: {ref(state.ref)}.",
        f"Recomputed SGD-only metrics: {money(reevaluation.liquidity_after_planned_outflows)} planned liquidity; {reevaluation.planned_runway.months} months expense-only runway.",
        "Income-dependent recalculation pending: " + ", ".join(r.value for r in reevaluation.pending_reasons) + ".",
        "Projected monthly net cashflow: **not calculated**. No exchange rate or financial verdict is fabricated.", "",
        f"Evidence history contains {len(snapshot.records)} immutable records across {snapshot.revision} committed operations.",
        "The JSON companion includes the source state, assumptions, options, calculations, goal/plan versions, consent, receipt, evidence, interpretation, event and re-evaluation.", "",
    ]
    return "\n".join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="Export complete structured history with exact rational values")
    args = parser.parse_args()
    snapshot = run_story().snapshot
    print(json.dumps(structured(snapshot), ensure_ascii=False, indent=2, sort_keys=True) if args.json else markdown(snapshot))


if __name__ == "__main__":
    main()
